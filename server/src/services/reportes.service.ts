import PDFDocument from 'pdfkit';
import { QueryResultRow } from 'pg';
import { pool } from '../db.js';

const ZONA_HORARIA = 'America/Mexico_City';
type IdiomaReporte = 'es' | 'en';

export interface SolicitudReporte {
  idSucursal: number;
  fechaInicio: string;
  fechaFin: string;
  correo: string;
  generadoPor: string;
  idioma: IdiomaReporte;
}

interface FilaVenta { total_ventas: string; importe_total: string; ticket_promedio: string; piezas_totales: string; }
interface FilaEmpleado { empleado: string; ventas: string; importe: string; piezas: string; }
interface FilaDiaria { fecha: string; ventas: string; importe: string; }
interface FilaPago { metodo: string; importe: string; }
interface FilaProducto { producto: string; piezas: string; importe: string; }

function ejecutarConsulta<T extends QueryResultRow>(sql: string, values: unknown[]) {
  return pool.query<T>(sql, values);
}

function formatoMoneda(valor: unknown, idioma: IdiomaReporte): string {
  const locale = idioma === 'en' ? 'en-US' : 'es-MX';
  return new Intl.NumberFormat(locale, {
    style: 'currency', currency: 'MXN', currencyDisplay: idioma === 'en' ? 'narrowSymbol' : 'symbol'
  }).format(Number(valor ?? 0));
}

function fechaBonita(fecha: string, idioma: IdiomaReporte): string {
  const [anio, mes, dia] = fecha.split('-').map(Number);
  const locale = idioma === 'en' ? 'en-US' : 'es-MX';
  return new Intl.DateTimeFormat(locale, { dateStyle: 'long', timeZone: ZONA_HORARIA })
    .format(new Date(Date.UTC(anio, mes - 1, dia, 18)));
}

async function crearPdf(datos: {
  sucursal: string; inicio: string; fin: string; generadoPor: string;
  idioma: IdiomaReporte;
  ventas: FilaVenta; empleados: FilaEmpleado[]; dias: FilaDiaria[]; pagos: FilaPago[]; productos: FilaProducto[];
}): Promise<Buffer> {
  const doc = new PDFDocument({ size: 'LETTER', margin: 48, bufferPages: true, info: { Title: datos.idioma === 'en' ? 'POS Olimpo Sales Report' : 'Reporte de ventas POS Olimpo', Author: 'POS Olimpo' } });
  const chunks: Buffer[] = [];
  const terminado = new Promise<Buffer>((resolve, reject) => {
    doc.on('data', chunk => chunks.push(Buffer.from(chunk)));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
  });

  const oro = '#b8945a';
  const oscuro = '#302519';
  const gris = '#71685d';
  const en = datos.idioma === 'en';
  const locale = en ? 'en-US' : 'es-MX';
  const texto = en ? {
    titulo: 'OLIMPO · SALES REPORT', periodo: 'Period', generadoPor: 'Generated by', ventas: 'Sales',
    ingresos: 'Sales revenue', ticket: 'Average ticket', piezas: 'Pieces sold', grafica: 'Sales by period',
    sinVentas: 'No sales recorded for this period.', empleados: 'Employee performance', empleado: 'Employee',
    metodos: 'Payment methods', metodo: 'Method', importe: 'Amount', productos: 'Top-selling products', producto: 'Product',
    sales: 'Sales', pieces: 'Pieces', efectivo: 'Cash', debito: 'Debit card', credito: 'Credit card', transferencia: 'Transfer'
  } : {
    titulo: 'OLIMPO · REPORTE DE VENTAS', periodo: 'Periodo', generadoPor: 'Generado por', ventas: 'Ventas',
    ingresos: 'Ingresos por ventas', ticket: 'Ticket promedio', piezas: 'Piezas vendidas', grafica: 'Ventas por periodo',
    sinVentas: 'Sin ventas registradas para este periodo.', empleados: 'Desempeño por empleado', empleado: 'Empleado',
    metodos: 'Métodos de pago', metodo: 'Método', importe: 'Importe', productos: 'Productos más vendidos', producto: 'Producto',
    sales: 'Ventas', pieces: 'Piezas', efectivo: 'Efectivo', debito: 'Tarjeta de débito', credito: 'Tarjeta de crédito', transferencia: 'Transferencia'
  };
  const metodoPago = (metodo: string) => ({ efectivo: texto.efectivo, debito: texto.debito, credito: texto.credito, transferencia: texto.transferencia }[metodo] ?? metodo);
  const ancho = doc.page.width - 96;
  const yFinal = doc.page.height - 86;
  let y = 48;
  const nuevaPagina = () => { doc.addPage(); y = 48; };
  const espacio = (alto: number) => { if (y + alto > yFinal) nuevaPagina(); };

  const total = Number(datos.ventas.importe_total ?? 0);
  const ventas = Number(datos.ventas.total_ventas ?? 0);
  doc.fillColor(oscuro).font('Helvetica-Bold').fontSize(20)
    .text(texto.titulo, 48, y, { width: ancho, align: 'left', lineBreak: false, ellipsis: true });
  y += 29;
  doc.fillColor(oro).font('Helvetica-Bold').fontSize(13)
    .text(datos.sucursal, 48, y, { width: ancho, align: 'left', lineBreak: false, ellipsis: true });
  y += 19;
  doc.fillColor(gris).font('Helvetica').fontSize(9)
    .text(`${texto.periodo}: ${fechaBonita(datos.inicio, datos.idioma)} ${en ? 'to' : 'al'} ${fechaBonita(datos.fin, datos.idioma)}`, 48, y, { width: ancho, align: 'left', lineBreak: false });
  y += 14;
  doc.text(`${texto.generadoPor}: ${datos.generadoPor} · ${new Date().toLocaleString(locale, { timeZone: ZONA_HORARIA })}`, 48, y, { width: ancho, align: 'left', lineBreak: false, ellipsis: true });
  y += 26;

  const kpis = [
    [texto.ventas, String(ventas)], [texto.ingresos, formatoMoneda(total, datos.idioma)],
    [texto.ticket, formatoMoneda(datos.ventas.ticket_promedio, datos.idioma)],
    [texto.piezas, String(datos.ventas.piezas_totales ?? 0)]
  ];
  const kpiW = ancho / kpis.length;
  kpis.forEach(([label, value], i) => {
    const x = 48 + i * kpiW;
    doc.roundedRect(x, y, kpiW - 8, 54, 5).fill('#f5f0e7');
    doc.fillColor(gris).font('Helvetica').fontSize(8).text(label, x + 9, y + 10, { width: kpiW - 25, align: 'left', lineBreak: false, ellipsis: true });
    doc.fillColor(oscuro).font('Helvetica-Bold').fontSize(12).text(value, x + 9, y + 29, { width: kpiW - 25, align: 'left', lineBreak: false, ellipsis: true });
  });
  y += 70;

  espacio(150);
  doc.fillColor(oscuro).font('Helvetica-Bold').fontSize(13)
    .text(texto.grafica, 48, y, { width: ancho, align: 'left', lineBreak: false });
  y += 24;
  let chartData: Array<{ fecha: string; importe: number }>;
  const longitudRango = (Date.parse(`${datos.fin}T00:00:00Z`) - Date.parse(`${datos.inicio}T00:00:00Z`)) / 86_400_000;
  const graficaMensual = longitudRango > 62;
  if (graficaMensual) {
    const porMes = new Map<string, number>();
    for (const dia of datos.dias) {
      const mes = dia.fecha.slice(0, 7);
      porMes.set(mes, (porMes.get(mes) ?? 0) + Number(dia.importe));
    }
    chartData = [...porMes].map(([fecha, importe]) => ({ fecha, importe }));
  } else {
    chartData = datos.dias.map(dia => ({ fecha: dia.fecha.slice(5), importe: Number(dia.importe) }));
  }
  const chartTop = y;
  const chartH = 84;
  const chartMax = Math.max(1, ...chartData.map(d => d.importe));
  const barGap = chartData.length > 20 ? 3 : 8;
  const barW = chartData.length ? Math.max(4, (ancho - barGap * (chartData.length - 1)) / chartData.length) : ancho;
  chartData.forEach((bar, index) => {
    const x = 48 + index * (barW + barGap);
    const h = Math.max(2, (bar.importe / chartMax) * 68);
    doc.roundedRect(x, chartTop + 70 - h, barW, h, 1.5).fill(oro);
    const mostrarEtiqueta = chartData.length <= 14 || (chartData.length <= 31 && index % 5 === 0);
    if (mostrarEtiqueta) {
      const etiqueta = graficaMensual
        ? new Intl.DateTimeFormat(locale, { month: 'short', timeZone: ZONA_HORARIA }).format(new Date(`${bar.fecha}-01T18:00:00Z`))
        : bar.fecha;
      doc.fillColor(gris).font('Helvetica').fontSize(7)
        .text(etiqueta, x - 2, chartTop + 74, { width: barW + 4, align: 'center', lineBreak: false, ellipsis: true });
    }
  });
  if (!chartData.length) {
    doc.fillColor(gris).font('Helvetica').fontSize(9)
      .text(texto.sinVentas, 48, chartTop + 22, { width: ancho, align: 'center', lineBreak: false });
  }
  y = chartTop + chartH;

  const seccion = (titulo: string) => {
    espacio(68);
    doc.fillColor(oscuro).font('Helvetica-Bold').fontSize(13)
      .text(titulo, 48, y, { width: ancho, align: 'left', lineBreak: false });
    y += 22;
  };
  const tabla = (encabezados: string[], filas: string[][], anchos: number[]) => {
    const x0 = 48;
    const filaH = 21;
    const dibujarFila = (celdas: string[], encabezado = false) => {
      const filaY = y;
      if (encabezado) doc.rect(x0, filaY, ancho, filaH).fill('#eee5d5');
      let x = x0;
      celdas.forEach((valor, idx) => {
        const w = anchos[idx];
        doc.fillColor(encabezado ? oscuro : gris).font(encabezado ? 'Helvetica-Bold' : 'Helvetica').fontSize(9)
          .text(valor, x + 5, filaY + 6, { width: w - 10, align: idx === celdas.length - 1 ? 'right' : 'left', lineBreak: false, ellipsis: true });
        x += w;
      });
      y = filaY + filaH;
    };
    if (filas.length && y + filaH * 2 > yFinal) nuevaPagina();
    dibujarFila(encabezados, true);
    for (const fila of filas) {
      if (y + filaH > yFinal) {
        nuevaPagina();
        dibujarFila(encabezados, true);
      }
      dibujarFila(fila);
    }
  };

  seccion(texto.empleados);
  const empleadosConVentas = datos.empleados.filter(e => Number(e.importe) > 0).slice(0, 8);
  if (empleadosConVentas.length) {
    const maxEmpleado = Math.max(...empleadosConVentas.map(e => Number(e.importe)));
    empleadosConVentas.forEach(e => {
      espacio(18);
      doc.fillColor(gris).font('Helvetica').fontSize(8).text(e.empleado, 48, y, { width: 145, align: 'left', lineBreak: false, ellipsis: true });
      doc.roundedRect(198, y + 1, ancho - 260, 10, 3).fill('#eee5d5');
      doc.roundedRect(198, y + 1, Math.max(2, (Number(e.importe) / maxEmpleado) * (ancho - 260)), 10, 3).fill(oro);
      doc.fillColor(oscuro).font('Helvetica-Bold').fontSize(8).text(formatoMoneda(e.importe, datos.idioma), 48 + ancho - 105, y, { width: 105, align: 'right', lineBreak: false });
      y += 17;
    });
  } else {
    doc.fillColor(gris).font('Helvetica').fontSize(9).text('Sin ventas registradas para este periodo.', 48, y, { width: ancho, align: 'left', lineBreak: false });
    y += 15;
  }
  tabla([texto.empleado, texto.sales, texto.pieces, texto.importe], datos.empleados.map(e => [e.empleado, e.ventas, e.piezas, formatoMoneda(e.importe, datos.idioma)]), [ancho * .46, ancho * .16, ancho * .16, ancho * .22]);

  seccion(texto.metodos);
  tabla([texto.metodo, texto.importe], datos.pagos.map(p => [metodoPago(p.metodo), formatoMoneda(p.importe, datos.idioma)]), [ancho * .65, ancho * .35]);

  seccion(texto.productos);
  tabla([texto.producto, texto.pieces, texto.importe], datos.productos.slice(0, 10).map(p => [p.producto, p.piezas, formatoMoneda(p.importe, datos.idioma)]), [ancho * .55, ancho * .18, ancho * .27]);

  const paginas = doc.bufferedPageRange();
  for (let i = 0; i < paginas.count; i++) {
    doc.switchToPage(i);
    doc.save();
    doc.moveTo(48, 724).lineTo(doc.page.width - 48, 724).strokeColor('#e3d9c8').stroke();
    doc.fillColor(gris).font('Helvetica').fontSize(8).text(`POS Olimpo · ${datos.sucursal}`, 48, 729, { width: ancho * .7, align: 'left', lineBreak: false, ellipsis: true });
    doc.text(`${en ? 'Page' : 'Página'} ${i + 1} ${en ? 'of' : 'de'} ${paginas.count}`, 48 + ancho * .7, 729, { width: ancho * .3, align: 'right', lineBreak: false });
    doc.restore();
  }
  doc.end();
  return terminado;
}

export async function prepararReporte(solicitud: SolicitudReporte): Promise<{
  archivo: string; buffer: Buffer; sucursal: string; correo: string; ventas: number; total: number;
}> {
  const values = [solicitud.idSucursal, solicitud.fechaInicio, solicitud.fechaFin];
  const filtroFecha = `v.fecha_venta >= ($2::date::timestamp AT TIME ZONE '${ZONA_HORARIA}')
    AND v.fecha_venta < (($3::date + 1)::timestamp AT TIME ZONE '${ZONA_HORARIA}')`;
  const { rows: sucursales } = await pool.query<{ nombre: string }>('SELECT nombre FROM sucursales WHERE id = $1 AND activa = true', [solicitud.idSucursal]);
  if (!sucursales.length) throw new Error('SUCURSAL_NO_ENCONTRADA');

  const [resumen, empleados, dias, pagos, productos] = await Promise.all([
    ejecutarConsulta<FilaVenta>(`SELECT COUNT(*)::text AS total_ventas, COALESCE(SUM(v.total), 0)::text AS importe_total,
      COALESCE(AVG(v.total), 0)::text AS ticket_promedio,
      COALESCE((SELECT SUM(dv.cantidad) FROM detalle_ventas dv JOIN ventas vp ON vp.id = dv.id_venta
        WHERE vp.id_sucursal = $1 AND vp.estado = 'Completada'
          AND vp.fecha_venta >= ($2::date::timestamp AT TIME ZONE '${ZONA_HORARIA}')
          AND vp.fecha_venta < (($3::date + 1)::timestamp AT TIME ZONE '${ZONA_HORARIA}')), 0)::text AS piezas_totales
      FROM ventas v WHERE v.id_sucursal = $1 AND v.estado = 'Completada' AND ${filtroFecha}`, values),
    ejecutarConsulta<FilaEmpleado>(`SELECT concat_ws(' ', u.nombres, u.apellido_paterno, u.apellido_materno) AS empleado,
      COUNT(v.id)::text AS ventas, COALESCE(SUM(v.total), 0)::text AS importe,
      COALESCE(SUM(d.piezas), 0)::text AS piezas
      FROM usuarios u LEFT JOIN ventas v ON v.id_usuario = u.id AND v.id_sucursal = $1 AND v.estado = 'Completada' AND ${filtroFecha}
      LEFT JOIN LATERAL (SELECT SUM(dv.cantidad) AS piezas FROM detalle_ventas dv WHERE dv.id_venta = v.id) d ON true
      WHERE u.id_sucursal = $1 AND u.activo = true GROUP BY u.id, u.nombres, u.apellido_paterno, u.apellido_materno
      ORDER BY SUM(v.total) DESC NULLS LAST, empleado`, values),
    ejecutarConsulta<FilaDiaria>(`SELECT to_char(v.fecha_venta AT TIME ZONE '${ZONA_HORARIA}', 'YYYY-MM-DD') AS fecha,
      COUNT(*)::text AS ventas, SUM(v.total)::text AS importe FROM ventas v WHERE v.id_sucursal = $1 AND v.estado = 'Completada' AND ${filtroFecha}
      GROUP BY 1 ORDER BY 1`, values),
    ejecutarConsulta<FilaPago>(`SELECT pv.metodo, SUM(pv.monto)::text AS importe FROM pagos_venta pv JOIN ventas v ON v.id = pv.id_venta
      WHERE v.id_sucursal = $1 AND v.estado = 'Completada' AND ${filtroFecha} GROUP BY pv.metodo ORDER BY SUM(pv.monto) DESC`, values),
    ejecutarConsulta<FilaProducto>(`SELECT p.nombre AS producto, SUM(dv.cantidad)::text AS piezas, SUM(dv.subtotal_linea)::text AS importe
      FROM detalle_ventas dv JOIN ventas v ON v.id = dv.id_venta JOIN productos p ON p.id = dv.id_producto
      WHERE v.id_sucursal = $1 AND v.estado = 'Completada' AND ${filtroFecha} GROUP BY p.id, p.nombre
      ORDER BY SUM(dv.cantidad) DESC, SUM(dv.subtotal_linea) DESC LIMIT 10`, values)
  ]);

  const buffer = await crearPdf({
    sucursal: sucursales[0].nombre, inicio: solicitud.fechaInicio, fin: solicitud.fechaFin,
    generadoPor: solicitud.generadoPor, idioma: solicitud.idioma,
    ventas: resumen.rows[0], empleados: empleados.rows,
    dias: dias.rows, pagos: pagos.rows, productos: productos.rows
  });
  const archivo = `reporte-${solicitud.fechaInicio}-a-${solicitud.fechaFin}.pdf`;
  return {
    archivo, buffer, sucursal: sucursales[0].nombre, correo: solicitud.correo,
    ventas: Number(resumen.rows[0]?.total_ventas ?? 0), total: Number(resumen.rows[0]?.importe_total ?? 0)
  };
}
